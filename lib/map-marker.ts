/**
 * Крест на карте — один на обе карты.
 *
 * Раньше их было два. Команда видела крест, нарисованный SVG, а
 * организатор — квадрат с `clip-path` в инлайновом стиле. Второй
 * не пережил сборку: из строки со стилем пропадал кусок с
 * `clip-path`, `background` слипался со следующим свойством в одно
 * невалидное объявление, и в браузер приезжал прозрачный квадрат
 * 28×28. В разметке маркер был, на карте — нет.
 *
 * Симптом со стороны организатора звучал так: «когда ставим
 * координаты, мы не знаем точной точки, не видим визуальной». Он и
 * не мог: крест был невидим ровно на том экране, где по нему
 * принимают решение.
 *
 * Отсюда правило: маркер рисуется геометрией SVG, а не свойством
 * CSS, которое может не пережить минификацию. Инлайновый стиль
 * остаётся только там, где это одно-два простых свойства.
 *
 * И заодно организатор теперь видит ровно тот знак, который увидит
 * команда: сверять карту с игрой стало нечем.
 */

export const CROSS_SIZE = 34;

/**
 * Крест из двух перечёркнутых линий.
 *
 * Обводка цветом полотна идёт первой и толще: на светлой плитке
 * карты розовый крест без неё сливается с фоном.
 */
export function crossSvg(color: string, outline: string): string {
  return (
    `<svg width="${CROSS_SIZE}" height="${CROSS_SIZE}" ` +
    `viewBox="0 0 ${CROSS_SIZE} ${CROSS_SIZE}" fill="none" aria-hidden="true">` +
    `<path d="M9 9 25 25M25 9 9 25" stroke="${outline}" stroke-width="7" stroke-linecap="round"/>` +
    `<path d="M9 9 25 25M25 9 9 25" stroke="${color}" stroke-width="3.4" stroke-linecap="round"/>` +
    `</svg>`
  );
}
