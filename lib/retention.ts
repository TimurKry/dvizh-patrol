/**
 * Граница срока хранения фотографий.
 *
 * Вынесено из компонента намеренно: обращение к текущему времени
 * в теле серверного компонента делает отрисовку зависящей от
 * момента вызова, и линтер справедливо на это ругается.
 * Здесь же это обычная функция с явным входом и выходом.
 */
export function retentionCutoff(days: number, now: Date = new Date()): string {
  return new Date(now.getTime() - days * 86_400_000).toISOString();
}
