import type { TeamRow } from '@/types/database';

/**
 * Режим доступа команды.
 *
 * В базе это не одно поле, а пара: `is_test` — «не забирает
 * задания из пула и играет вне статуса», `full_pool` — «весь пул
 * на руке вместо шести». Пара выбрана вместо перечисления
 * намеренно: `is_test` уже стоит на отправках, участвует в
 * исключении из рейтинга и в захвате заданий, и переезд на enum
 * тронул бы всё это ради переименования.
 *
 * Наружу пара не выходит — везде, где нужен режим, спрашивают
 * `teamAccess()`. Иначе комбинация «is_test без full_pool» будет
 * заново расшифровываться на каждом экране, и однажды кто-нибудь
 * расшифрует её иначе.
 */

export const TEAM_ACCESS = ['normal', 'alpha', 'preview'] as const;

export type TeamAccess = (typeof TEAM_ACCESS)[number];

export function isTeamAccess(value: unknown): value is TeamAccess {
  return typeof value === 'string' && (TEAM_ACCESS as readonly string[]).includes(value);
}

export function teamAccess(team: Pick<TeamRow, 'is_test' | 'full_pool'>): TeamAccess {
  if (!team.is_test) return 'normal';
  return team.full_pool ? 'preview' : 'alpha';
}

interface AccessSpec {
  /** Короткая метка: список команд, шапка карточки, строка отправки. */
  readonly tag: string;
  /** Название режима в переключателе. */
  readonly label: string;
  /** Что означает — для организатора, в админке. */
  readonly admin: string;
  /** Что означает — для участника, на экране заданий. */
  readonly player: string | null;
  /** Подтверждение при переключении. */
  readonly confirm: string;
}

