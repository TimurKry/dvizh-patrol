-- ─────────────────────────────────────────────────────────────
-- 0012 — Мероприятие переехало на 5 сентября
--
-- Решение владельца. Дата и время живут только в `events`:
-- лендинг, отсчёт, og-превью и экраны участника берут их оттуда
-- и больше нигде не дублируются, поэтому миграция состоит из
-- одного UPDATE.
--
-- 14:00 Europe/Berlin — в сентябре это ещё летнее время, UTC+2,
-- то есть 12:00 UTC. Записываем со смещением, а не в UTC:
-- смещение читается глазами и переживёт перенос на другую дату.
-- ─────────────────────────────────────────────────────────────

UPDATE public.events
SET starts_at = timestamptz '2026-09-05 14:00:00+02'
WHERE slug = 'leipzig-2026';
