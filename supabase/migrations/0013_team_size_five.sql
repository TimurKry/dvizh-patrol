-- 0013 · Команда из пяти человек
--
-- Владелец увеличил состав: капитан плюс четверо. Потолок в
-- четыре человека стоял в CHECK-ограничении, поэтому одной
-- правкой значения не обойтись — сначала расширяется диапазон.
--
-- Верхняя граница поднята до шести, а не до пяти. Ограничение
-- существует, чтобы отсечь опечатку в админке (пятьдесят вместо
-- пяти), а не чтобы зафиксировать ровно текущее решение: если
-- владелец захочет шестого, это должно быть правкой поля в
-- интерфейсе, а не новой миграцией в пятницу вечером.
--
-- Уже зарегистрированные команды правка не трогает: лимит
-- проверяется при вступлении нового участника, а не задним
-- числом.
-- ═══════════════════════════════════════════════════════════════

ALTER TABLE public.events
  DROP CONSTRAINT IF EXISTS events_team_size_range;

ALTER TABLE public.events
  ADD CONSTRAINT events_team_size_range CHECK (team_size BETWEEN 1 AND 6);

ALTER TABLE public.events
  ALTER COLUMN team_size SET DEFAULT 5;

