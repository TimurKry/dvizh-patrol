-- 0016 · Что почитать по дороге
--
-- До сих пор у задания был только `afterword` — рассказ, который
-- открывается после отправки. Он закрывает вечер, но не занимает
-- дорогу: до точки идти десять-пятнадцать минут, и всё это время
-- в телефоне нечего читать, кроме условия в две строки.
--
-- `backstory` — короткая справка, видная сразу: биография того,
-- кому памятник, история дома, чем известно место. Человек читает
-- её, пока идёт, и приходит к объекту, уже зная, на что смотрит.
--
-- Два поля, а не одно с переключателем «когда показывать»,
-- потому что это разные тексты и они не исключают друг друга:
-- по дороге — кто это, после отправки — что здесь произошло и
-- ссылка на статью.
--
-- **Для загадки справка почти всегда спойлер.** Биография Гёте
-- рядом с загадкой «тот, кто вписал город в свою книгу» решает её
-- за команду. Запрета в базе нет — бывают загадки, где справка
-- уместна и ничего не выдаёт, — но админка об этом предупреждает.
-- ═══════════════════════════════════════════════════════════════

ALTER TABLE public.tasks
  ADD COLUMN IF NOT EXISTS backstory text;

COMMENT ON COLUMN public.tasks.backstory IS
  'Справка, видная сразу: что это за место, кому памятник. Читается по дороге. Для загадки обычно спойлер.';
