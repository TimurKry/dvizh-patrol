-- 0017 · Примеры на лендинге выбираются в админке
--
-- Три карточки-примера на лендинге были зашиты в код. Любая правка
-- — «этот пример невыполним», «поставь другое задание», «покажи
-- тут карту» — упиралась в меня и выкладку. Теперь организатор
-- ставит заданию номер слота и видит его на лендинге сразу.
--
-- Слот, а не флаг: их ровно три, и порядок важен — карточки стоят
-- в ряд, и решать, какая слева, должен организатор, а не сортировка
-- по номеру задания.
--
-- Золотая карточка остаётся в коде: «обменять стикер» — не задание
-- из пула, а неподвижное продуктовое решение (CLAUDE.md), и она
-- одна на всё мероприятие.
--
-- **Слот делает задание публичным.** Лендинг открыт всем, и всё,
-- что попало в слот, читается до старта: и формулировка, и
-- фото-эталон, и точка на карте. Для загадки это значит, что её
-- решат заранее. Поэтому в слоты идут либо задания, которые не
-- жалко раскрыть, либо выключенные (`active = false`) карточки,
-- сделанные специально для витрины: выключенное задание в руки не
-- раздаётся, но на лендинге показывается.
-- ═══════════════════════════════════════════════════════════════

ALTER TABLE public.tasks
  ADD COLUMN IF NOT EXISTS landing_slot smallint;

ALTER TABLE public.tasks DROP CONSTRAINT IF EXISTS tasks_landing_slot_range;
ALTER TABLE public.tasks
  ADD CONSTRAINT tasks_landing_slot_range CHECK (
    landing_slot IS NULL OR landing_slot BETWEEN 1 AND 3
  );

-- Один слот — одно задание. Частичный индекс: NULL сколько угодно.
DROP INDEX IF EXISTS tasks_landing_slot_key;
CREATE UNIQUE INDEX tasks_landing_slot_key
  ON public.tasks (event_id, landing_slot)
  WHERE landing_slot IS NOT NULL;

COMMENT ON COLUMN public.tasks.landing_slot IS
  'Место в витрине лендинга: 1..3 слева направо, NULL — не показывать. Слот делает задание публичным до старта.';
