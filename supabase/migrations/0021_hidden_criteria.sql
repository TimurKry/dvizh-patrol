-- 0021 · Скрытые критерии: то, что знает судья, но не знает команда
--
-- Критерии проверки видны команде — и это правильно: человек
-- должен понимать, что от него хотят, а не угадывать. Но у загадки
-- ровно это и ломает всё: критерий «на фото памятник Фаусту» —
-- готовый ответ, напечатанный под условием.
--
-- Из-за этого все семнадцать загадок стояли на ручной проверке. До
-- модели они не доходили вовсе, и организатор оказывался узким
-- местом собственного вечера: пока он не откроет очередь, команда
-- не получает ни баллов, ни новой карточки.
--
-- Теперь у задания два набора критериев. Открытые — прежние, их
-- читает команда. Скрытые уходят только в запрос к модели и не
-- покидают сервер: ни в руке, ни на странице задания, ни в
-- выгрузке их нет.
--
-- Это не «секрет ради секрета». Проверять фотографию и объяснять
-- задание — разные тексты, и попытка написать один текст на две
-- роли всегда портит какую-нибудь из них.
-- ═══════════════════════════════════════════════════════════════

ALTER TABLE public.tasks
  ADD COLUMN IF NOT EXISTS hidden_criteria jsonb NOT NULL DEFAULT '[]'::jsonb;

-- Тот же вид, что у открытых критериев: массив строк.
ALTER TABLE public.tasks DROP CONSTRAINT IF EXISTS tasks_hidden_criteria_shape;
ALTER TABLE public.tasks
  ADD CONSTRAINT tasks_hidden_criteria_shape CHECK (
    jsonb_typeof(hidden_criteria) = 'array'
    AND jsonb_array_length(hidden_criteria) <= 12
  );

COMMENT ON COLUMN public.tasks.hidden_criteria IS
  'Критерии только для модели. Команде не показываются нигде: у загадки открытый критерий назвал бы ответ.';
