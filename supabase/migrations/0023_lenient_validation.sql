-- 0023 · Проверка перестаёт создавать работу организатору
--
-- Первая настоящая проверка прошла успешно и показала, чего стоит
-- строгость. Фотография с чётко читаемым номером дома получила
-- 0.99 по главному критерию — и всё равно легла в ручную очередь:
-- второй критерий требовал видеть, что табличка висит на здании, а
-- номер дома снимают крупным планом, и здание в такой кадр не
-- попадает. Итог 0.75 при пороге 0.88.
--
-- Решение владельца: сократить проверку до минимума. У него вечером
-- квеста не будет времени разбирать очередь, а команды играть
-- заинтересованы сами и обманывать судью не пытаются.
--
-- Здесь две части: порог и критерии. Третья — доброжелательность
-- самой модели — живёт в системной инструкции `lib/ai/gemini.ts`,
-- потому что порог не помогает, пока модель сама отвечает
-- «manual_review».

-- ═══ Порог ═══════════════════════════════════════════════════

ALTER TABLE public.events ALTER COLUMN ai_accept_threshold SET DEFAULT 0.5;

UPDATE public.events SET ai_accept_threshold = 0.5;

-- ═══ Критерии ════════════════════════════════════════════════
--
-- Правило, по которому переписано: один критерий — то главное, ради
-- чего задание придумано. Всё остальное убрано.
--
-- Требования вида «в кадре минимум два участника» удалены не
-- потому, что перестали действовать, а потому, что они дублировали
-- поле `minimum_people`: оно уходит в модель отдельной строкой и
-- проверяется без критерия. Значения самого поля не тронуты.
--
-- Задания на ручной проверке не тронуты вовсе: их критерии читает
-- человек, а не модель, и владелец правит их сам.

UPDATE public.tasks SET criteria = c.criteria::jsonb
FROM (VALUES
  ( 1, '["В кадре полицейский или полицейская машина"]'),
  ( 3, '["В кадре музыкальный инструмент"]'),
  ( 6, '["В кадре фонтан"]'),
  ( 7, '["В кадре граффити-рисунок"]'),
  ( 8, '["Главное в кадре — отражение"]'),
  ( 9, '["Здание из эталонного кадра узнаётся"]'),
  (10, '["В кадре пять разных животных"]'),
  (12, '["В кадре чаша"]'),
  (13, '["В кадре читается номер дома: 7, 13 или 21"]'),
  (14, '["В кадре пять жёлтых предметов"]'),
  (16, '["В кадре пять флагов"]'),
  (17, '["Буква с фасада попадает на раскрытую ладонь"]'),
  (18, '["В кадре человек играет на музыкальном инструменте"]'),
  (23, '["В кадре треугольный знак дорожных работ"]'),
  (26, '["В кадре церковь"]'),
  (27, '["В кадре бронзовые фигуры"]'),
  (28, '["В кадре церковь"]'),
  (33, '["В кадре эркер — выступ фасада с окнами"]'),
  (38, '["В кадре круглое окно или витраж"]'),
  (42, '["В кадре круглый камень"]'),
  (45, '["В кадре живые цветы"]'),
  (51, '["В кадре памятник"]'),
  (52, '["В кадре памятник"]')
) AS c(number, criteria)
WHERE public.tasks.number = c.number
  AND public.tasks.validation_mode = 'ai';
