-- 0024 · Все задания уходят на автоматическую проверку
--
-- Владелец заполняет задания и просит снять с себя ручную очередь:
-- «сейчас вручную каждое перепроверять будет достаточно долго».
-- Восемнадцать заданий стояли на ручном режиме — это и был весь
-- оставшийся объём его вечерней работы.
--
-- Задание №21 оставлено в режиме `auto` («принимать сразу»): он и
-- так не требует ничего от организатора, переводить его в `ai`
-- значило бы добавить проверку там, где её нет.

-- ═══ Ограничение под скрытые критерии ════════════════════════
--
-- В 0021 у загадки появился второй список критериев — скрытый,
-- чтобы открытый не печатал ответ под условием. Требование
-- «для автопроверки нужен критерий» тогда научилось принимать
-- любой из двух списков, но только в схеме формы. В базе осталась
-- прежняя проверка, и загадка с одними скрытыми критериями
-- падала бы на ограничении при сохранении.

ALTER TABLE public.tasks DROP CONSTRAINT IF EXISTS tasks_ai_needs_criteria;

ALTER TABLE public.tasks
  ADD CONSTRAINT tasks_ai_needs_criteria CHECK (
    validation_mode <> 'ai'
    OR jsonb_array_length(criteria) > 0
    OR jsonb_array_length(hidden_criteria) > 0
  );

-- ═══ Критерии, которые модели не по зубам ════════════════════
--
-- №41 требовал «кадр снят вами сегодня, а не взят из интернета».
-- Это не проверяется по фотографии никакой моделью: на ручном
-- режиме такой критерий читал человек, на автоматическом он стал
-- бы либо вечным manual_review, либо пустой формальностью.

UPDATE public.tasks
SET criteria = '["В кадре городской вид Лейпцига"]'::jsonb
WHERE number = 41;

-- ═══ Ответ загадки уезжает в скрытые критерии ════════════════
--
-- №2 называется «Памятник композитора», а в открытом критерии
-- стояло «На фотографии виден памятник Баху» — ответ, напечатанный
-- под условием. Ровно для этого в 0021 и заведён скрытый список:
-- судья ответ знает, команда его не видит. Участника в кадре
-- обеспечивает поле `minimum_people`, оно и так равно единице.

UPDATE public.tasks
SET criteria = '[]'::jsonb,
    hidden_criteria = '["На фотографии виден памятник Баху"]'::jsonb
WHERE number = 2;

-- ═══ Один критерий на задание ════════════════════════════════
--
-- То же правило, что в 0023: остаётся то главное, ради чего
-- задание придумано. Каждый лишний критерий — отдельная дверь в
-- ручную очередь: невыполненный критерий пересиливает вердикт
-- модели в обход порога.
--
-- Требования про участников в кадре убраны как дубли поля
-- `minimum_people`; запреты «не лезть в воду» и «не забираться на
-- скульптуру» остаются в описаниях заданий, где команда их и
-- читает.

UPDATE public.tasks SET criteria = c.criteria::jsonb
FROM (VALUES
  (25, '["В кадре табличка"]'),
  (29, '["В коллаже три разных пассажа"]'),
  (32, '["Одним кадром сняты здания заметно разных эпох"]'),
  (43, '["В кадре циферблат часов"]'),
  (44, '["В кадре скамейка"]'),
  (46, '["В кадре фонтан"]'),
  (49, '["В кадре ряд колонн"]'),
  (50, '["В кадре фигура в мостовой"]')
) AS c(number, criteria)
WHERE public.tasks.number = c.number;

-- ═══ Переключение режима ═════════════════════════════════════

UPDATE public.tasks
SET validation_mode = 'ai'
WHERE active = true
  AND validation_mode = 'manual';
