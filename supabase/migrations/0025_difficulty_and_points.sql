-- 0025 · Сложность и баллы по одному правилу
--
-- Владелец: «некоторые задания, которые простые, у них много
-- баллов, а у сложных может быть мало». Так и было: «просто» шло
-- от 50 до 150 баллов, а «сложно» — от 90 до 160. Сложность
-- ставилась на глаз и с баллами не связана.
--
-- Правило, по которому пересчитано. Балл складывается из двух
-- частей, и обе видны в таблице ниже.
--
--   НАЙТИ — сколько подсказки дано:
--     точка на карте, либо объект встречается повсюду ....  40
--     район на карте .....................................  80
--     конкретный объект без карты, искать по городу ...... 120
--
--   СДЕЛАТЬ — сколько работы в самом кадре:
--     обычный снимок .....................................  10
--     командная постановка, повтор эталона или коллаж ....  40
--
-- Отсюда в ходу пять значений: 50, 80, 90, 120 и 130. Шестое,
-- 160, пока пустует — сложного задания с постановкой в наборе нет.
-- Сложность берётся из первой части: она про поиск, а не про позу.
--
-- Главное следствие: задание с точкой на карте больше не может
-- стоить дороже задания, которое надо искать по всему городу.

