-- 0026 · Сложность считается по поиску, а не по позе
--
-- Правило владельца, дословно: «все задания, где нет заданной
-- точки, должны стоить больше, чем задания с заданной локацией
-- либо крестиком — это самые простые. Потом идут те, где
-- обозначено поле. И самое сложное — где нет конкретной локации».
--
-- В 0025 шкала была построена наоборот и вдобавок слишком
-- плоская: «сложных» заданий по сути не было. Здесь пять ступеней
-- поиска вместо трёх.
--
--   НАЙТИ
--     крестик на карте ...................................  30
--     объект встречается повсюду (флаг, цветы, граффити) .  50
--     район на карте .....................................  80
--     карты нет, но объект назван и есть эталонное фото .. 110
--     карты нет и объекта нет: нужен живой человек,
--       собственный выбор или несколько находок разом .... 140
--
--   СДЕЛАТЬ
--     обычный снимок .....................................  10
--     командная постановка, повтор эталона, коллаж
--       или договориться с посторонним человеком .........  40
--
-- Четвёртая ступень появилась из замечания владельца: №36 и №43
-- карты не имеют, но «на картинках прямо изображено, что надо
-- сфоткать, и как это называется». С эталонным фото объект без
-- карты ищется заметно легче, чем без него, — это отдельная
-- ступень, а не «сложно».
--
-- Сложность берётся только из первой части: она про поиск.
--   ступени 1–2 → easy, 3–4 → medium, 5 → hard.

UPDATE public.tasks SET difficulty = v.difficulty, points = v.points
FROM (VALUES
  -- ─── Крестик на карте, обычный снимок ──────── 40
  ( 2, 'easy',    40), ( 5, 'easy',    40),
  (31, 'easy',    40), (34, 'easy',    40),

  -- ─── Объект повсюду, обычный снимок ────────── 60
  ( 3, 'easy',    60), ( 7, 'easy',    60), ( 8, 'easy',    60),
  (10, 'easy',    60), (13, 'easy',    60), (14, 'easy',    60),
  (16, 'easy',    60), (33, 'easy',    60), (38, 'easy',    60),
  (41, 'easy',    60), (44, 'easy',    60), (45, 'easy',    60),

  -- ─── Крестик на карте, командная постановка ── 70
  ( 6, 'easy',    70), ( 9, 'easy',    70), (11, 'easy',    70),
  (12, 'easy',    70), (21, 'easy',    70), (26, 'easy',    70),
  (27, 'easy',    70), (28, 'easy',    70), (42, 'easy',    70),
  (46, 'easy',    70),

  -- ─── Район на карте, обычный снимок ────────── 90
  ( 4, 'medium',  90), (20, 'medium',  90), (25, 'medium',  90),
  (32, 'medium',  90), (37, 'medium',  90), (39, 'medium',  90),
  (40, 'medium',  90), (47, 'medium',  90), (48, 'medium',  90),
  (49, 'medium',  90), (50, 'medium',  90),

  -- ─── Район + постановка · назван без карты ── 120
  (22, 'medium', 120), (51, 'medium', 120), (52, 'medium', 120),
  (36, 'medium', 120), (43, 'medium', 120),

  -- ─── Назван без карты + постановка ─────────── 150
  (17, 'medium', 150), (23, 'medium', 150),

  -- ─── Ни карты, ни объекта ──────────────────── 150 / 180
  (18, 'hard',   150),   -- найти играющего музыканта — ещё и удача
  ( 1, 'hard',   180),   -- найти полицейского и договориться
  (29, 'hard',   180)    -- три разных пассажа плюс коллаж
) AS v(number, difficulty, points)
WHERE public.tasks.number = v.number;
