-- ═══ Круг как область ════════════════════════════════════════
--
-- Загадке нужен район, а не точка, и рисовать шестнадцать контуров
-- руками незачем: правильный круг вокруг объекта — ровно то, что
-- обещает режим «область». Функция остаётся в базе: следующие
-- загадки заводятся тем же способом.

CREATE OR REPLACE FUNCTION public.circle_polygon(
  p_lat numeric, p_lon numeric, p_radius_m integer, p_points integer DEFAULT 24
)
RETURNS jsonb
LANGUAGE sql
IMMUTABLE
SET search_path = ''
AS $$
  SELECT jsonb_build_object(
    'type', 'Polygon',
    'coordinates', jsonb_build_array(jsonb_agg(ring ORDER BY step))
  )
  FROM (
    SELECT step,
           jsonb_build_array(
             round((p_lon + (p_radius_m / (111320 * cos(radians(p_lat))))
                    * cos(2 * pi() * step / p_points))::numeric, 6),
             round((p_lat + (p_radius_m / 110574.0)
                    * sin(2 * pi() * step / p_points))::numeric, 6)
           ) AS ring
    FROM generate_series(0, p_points) AS step
  ) AS pts;
$$;

REVOKE ALL ON FUNCTION public.circle_polygon(numeric, numeric, integer, integer)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.circle_polygon(numeric, numeric, integer, integer)
  TO service_role;

