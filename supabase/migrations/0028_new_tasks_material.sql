-- 0028 · «По дороге» и «После отправки» для семнадцати новых
--
-- Владелец: «по образу того, что я делал, надо добавить не просто
-- краткое описание, но и полное, По дороге и После отправки».
--
-- Интонация взята из уже заполненных заданий: «Вы нашли X. Это…»,
-- дальше два-три факта и ссылка на статью. Справка «по дороге»
-- показывается вместе с условием, поэтому у загадок она написана
-- так, чтобы не называть объект: контекст эпохи вместо биографии.
-- Форма задания предупреждает об этом сама, и предупреждение
-- верное — «биография рядом с загадкой решает её за команду».
--
-- Заодно исправлено фактическое враньё в описании №69: группу
-- «Несвоевременные современники» сделал Бернд Гёбель, а не
-- Вольфганг Маттойер. Маттойер — автор «Шага столетия» из №11,
-- и в первой редакции описания я приписал ему обе работы.

